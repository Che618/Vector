// Run with Node.js. No network or third-party packages are required.
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const root = fs.existsSync(path.join(__dirname,'../dist/portal/operations.js')) ? '../dist' : '..';
const O = require(root+'/portal/operations.js');
const s = O.seed();
const first = O.simulate(s,O.defaultRule);
assert.deepEqual([first.gross,first.cost,first.reserve,first.net],[4229,422,634,3173]);
assert.throws(()=>O.settle(s,O.defaultRule),/待核验/);
const duplicate = s.events.find(e=>e.ref==='JOB-11-1' && e.state==='待核验');
assert.throws(()=>O.review(s,duplicate.id,true,'重复检查'),/已经确认/);
O.review(s,duplicate.id,false,'相同凭据');
const original=s.events.find(e=>e.ref==='JOB-11-3');
O.review(s,original.id,true,'有效调用');
assert.throws(()=>O.review(s,original.id,true,'二次确认'),/已处理/);
assert.throws(()=>O.simulate(s,{...O.defaultRule,weights:[10,10,10]}),/100/);
const old=JSON.stringify(s.batches[0]);
const cash=O.settle(s,O.defaultRule);
assert.equal(O.total(cash.rows.map(r=>r.amount)),cash.net);
assert.equal(cash.net+cash.reserve+cash.cost,cash.gross);
assert.equal(JSON.stringify(s.batches[1]),old);
assert.throws(()=>O.settle(s,O.defaultRule),/大于零/);
const before=O.balance(s,0),v=O.issue(s,0,0,1);
assert.equal(O.balance(s,0),before-120);
O.redeem(s,v.id,'REDEEM-TEST');
assert.equal(s.uses[0].amount,0);
assert.equal(s.uses[0].qty,100);
assert.equal(s.uses[0].voucher,v.id);
assert.throws(()=>O.redeem(s,v.id,'RCPT-AGAIN'),/已核销/);
assert.throws(()=>O.issue(s,3,1,100),/余额不足/);
const t=s.tasks[0]; let latest=O.balance(s,t.actor), reserve=O.reserveBalance(s);
O.submit(s,t.id,{version:'v1.3',qty:12,proof:'Q-1'});
assert.throws(()=>O.acceptTask(s,t.id,true,'检查'),/低于/);
O.acceptTask(s,t.id,false,'补齐 24 条');
O.submit(s,t.id,{version:'v1.3',qty:24,proof:'Q-2'});O.acceptTask(s,t.id,true,'清单一致');
assert.equal(O.balance(s,t.actor),latest+160);assert.equal(O.reserveBalance(s),reserve);
assert.equal(s.resources[0].version,'v1.3');
assert.equal(s.events.find(e=>e.id===t.event).batch,t.id);
assert.throws(()=>O.acceptTask(s,t.id,true,'重复验收'));
let u=O.registerUse(s,0,200,'J-NEW');assert.equal(u.version,'v1.3');
assert.throws(()=>O.registerUse(s,0,10,'J-NEW'),/已登记/);
let delivery={actor:0,r:0,qty:20,ref:'BASIC-1',proof:'QC-123',grade:'D'};
let e=O.declare(s,delivery);assert.throws(()=>O.review(s,e.id,true,'不得分'),/有效产出/);
assert.throws(()=>O.declare(s,delivery),/已登记/);
assert.throws(()=>O.plan(s,{...t,title:'超额',budget:1000000}),/不足/);
console.log('PASS: evidence, metering, weighted allocation, settlement conservation, immutable snapshots, rights redemption, supply acceptance and next-cycle use.');
